-- OCPP diagnostic audit trail (PR: feat/ocpp-diagnostic-logging).
-- Run on Supabase STAGING (then PROD at release) BEFORE deploying: staging uses ddl-auto: validate,
-- so the app refuses to start if these tables are missing. Safe to re-run.
--
-- These tables are append-only logs written by the backend. Payloads have idToken values masked and never
-- contain passwords, Authorization headers or secret hashes. Rows older than ocpp.logging.persistence
-- .retention-days (default 30) are deleted by a daily job.

-- Every OCPP WebSocket frame, in and out.
CREATE TABLE IF NOT EXISTS ocpp_message_log (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    charge_point_id VARCHAR(64)  NOT NULL,   -- the code from the URL; not a foreign key (unknown chargers are logged too)
    ws_session_id  VARCHAR(64),
    direction      VARCHAR(8)   NOT NULL,    -- IN (charger -> us) or OUT (us -> charger)
    action         VARCHAR(64),
    message_type   INTEGER,                  -- 2 CALL, 3 CALLRESULT, 4 CALLERROR; null if unparseable
    message_id     VARCHAR(64),
    payload        TEXT,
    payload_size   INTEGER      NOT NULL,
    received_at    TIMESTAMPTZ(3) NOT NULL,
    discovery      BOOLEAN      NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS idx_ocpp_msg_cp_time ON ocpp_message_log (charge_point_id, received_at);
CREATE INDEX IF NOT EXISTS idx_ocpp_msg_time    ON ocpp_message_log (received_at);

-- Handshake attempts, requests that never reached the handshake, connects, disconnects, reconnects, idle warnings.
CREATE TABLE IF NOT EXISTS ocpp_connection_log (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    charge_point_id  VARCHAR(64),
    ws_session_id    VARCHAR(64),
    event            VARCHAR(30)  NOT NULL,  -- HANDSHAKE_ACCEPTED, HANDSHAKE_REJECTED, REQUEST_NEAR_MISS, CONNECTED, DISCONNECTED, RECONNECT, IDLE_WARNING
    reason           VARCHAR(64),
    close_code       INTEGER,
    remote_addr      VARCHAR(64),
    forwarded_for    VARCHAR(255),
    offered_protocols VARCHAR(255),
    user_agent       VARCHAR(255),
    request_uri      VARCHAR(1000),
    http_status      INTEGER,
    detail           TEXT,
    created_at       TIMESTAMPTZ(3) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_ocpp_conn_cp_time ON ocpp_connection_log (charge_point_id, created_at);
CREATE INDEX IF NOT EXISTS idx_ocpp_conn_time    ON ocpp_connection_log (created_at);

-- Outcome of each command we sent (answered, rejected, timed out, lost to a disconnect).
CREATE TABLE IF NOT EXISTS ocpp_command_log (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    charge_point_id   VARCHAR(64)  NOT NULL,
    ws_session_id     VARCHAR(64),
    message_id        VARCHAR(64)  NOT NULL,
    action            VARCHAR(64)  NOT NULL,
    charge_session_id UUID,
    evse_id           INTEGER,
    connector_id      INTEGER,
    reason            VARCHAR(255),
    sent_at           TIMESTAMPTZ(3) NOT NULL,
    completed_at      TIMESTAMPTZ(3),
    latency_ms        BIGINT,
    outcome           VARCHAR(20)  NOT NULL, -- RESULT, ERROR, TIMED_OUT, DISCONNECTED, SEND_FAILED
    response_status   VARCHAR(64),
    reason_code       VARCHAR(64),
    error_code        VARCHAR(64),
    error_description VARCHAR(500),
    detail            TEXT
);
CREATE INDEX IF NOT EXISTS idx_ocpp_cmd_cp_time ON ocpp_command_log (charge_point_id, sent_at);
CREATE INDEX IF NOT EXISTS idx_ocpp_cmd_session ON ocpp_command_log (charge_session_id);

-- One row per charge session: the stop / Ended / connector-status / unlock sequence (lock evidence).
CREATE TABLE IF NOT EXISTS ocpp_session_evidence (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    charge_session_id   UUID,
    charge_point_id     VARCHAR(64)  NOT NULL,
    ocpp_transaction_id VARCHAR(64),
    summary             TEXT,
    events              TEXT,
    created_at          TIMESTAMPTZ(3) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_ocpp_evidence_session ON ocpp_session_evidence (charge_session_id);
CREATE INDEX IF NOT EXISTS idx_ocpp_evidence_time    ON ocpp_session_evidence (created_at);

-- Same rule as every other table: nobody but the backend's own database login can read them.
ALTER TABLE ocpp_message_log      ENABLE ROW LEVEL SECURITY;
ALTER TABLE ocpp_connection_log   ENABLE ROW LEVEL SECURITY;
ALTER TABLE ocpp_command_log      ENABLE ROW LEVEL SECURITY;
ALTER TABLE ocpp_session_evidence ENABLE ROW LEVEL SECURITY;
