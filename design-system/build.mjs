const escapeCell = (text) => String(text).replace(/\|/g, '\\|');
const table = (head, rows) => [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map((row) => `| ${row.map(escapeCell).join(' | ')} |`)].join('\n');

