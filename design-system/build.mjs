#!/usr/bin/env node
/**
 * Rebuilds the generated parts of the design system. tokens.json is the source; nothing here touches either app.
 *
 *   node design-system/build.mjs          TOKENS.md, index.html and the two preview stylesheets
 *   node design-system/build.mjs --docs   TOKENS.md and index.html only (no Tailwind needed)
 *
 * The stylesheets are made by each app's own Tailwind setup, so a preview looks exactly like the real thing:
 * run `npm install` in samjhana-admin and samjhana-web first.
 * samjhana-admin/src/__tests__/designSystem.test.js fails when the committed TOKENS.md or index.html are out of date.
 */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));

export function readTokens(dir = here) {
  return JSON.parse(fs.readFileSync(path.join(dir, 'tokens.json'), 'utf8'));
}

/** Each component folder: its group and card height (from the first line of its preview) and the first sentence of its guide. */
export function componentList(dir = here) {
  const base = path.join(dir, 'components');
  return fs.readdirSync(base, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort()
    .map((name) => {
      const preview = fs.readFileSync(path.join(base, name, 'preview.html'), 'utf8');
      const [, group, height] = preview.split('\n')[0].match(/group="([^"]+)" height=(\d+)/);
      const guide = fs.readFileSync(path.join(base, name, 'README.md'), 'utf8');
      const paragraph = guide.split('\n').find((line) => line.trim() && !line.startsWith('#')) ?? '';
      const summary = paragraph.split(/(?<=\.)\s/)[0];
      return { name, group, height: Number(height), summary };
    });
}

